  <h2>Hi I'm Unsinkable Sam</h2>
  <img src="https://upload.wikimedia.org/wikipedia/commons/thumb/d/d4/Oscar%2C_cat_from_the_German_ship_%27Bismarck%27.jpg/500px-Oscar%2C_cat_from_the_German_ship_%27Bismarck%27.jpg" />
  <p>Previously named Oscar, I was the ship's cat of the German battleship Bismarck. When the ship was sunk on 27 May 1941, only 116 crew members of over 2,200 survived. Oscar was picked up by the destroyer HMS Cossack, one of the ships responsible for destroying the Bismarck. Cossack herself was torpedoed and sunk on 24 October 1941, killing 159 of her crew; but Oscar again survived, was rescued and taken to Gibraltar. I became the ship's cat of HMS Ark Royal, which was torpedoed and sunk in November that year. Oscar was again rescued, but it was decided at that time to transfer him to a home on land. By now known as Unsinkable Sam because of surviving the three ship sinkings, I was given a new job as shore duty mouse-catcher in the office buildings of the Governor of Gibraltar because I still had "six lives to go".[41] I eventually was taken to the UK and spent the rest of his life at the 'Home for Sailors'. A portrait of him exists in the collections of the National Maritime Museum in Greenwich.[42]</>

    
  
  
 
